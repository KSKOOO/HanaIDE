function assertKnownPlatformMethods(label, methodNames) {
  const known = new Set(HANA_PLATFORM_METHOD_NAMES);
  const unknown = methodNames.filter((methodName) => !known.has(methodName));
  if (unknown.length > 0) {
    throw new Error(`${label} contains unknown Hana platform methods: ${unknown.join(", ")}`);
  }
}

assertKnownPlatformMethods("Web fallback contract", HANA_PLATFORM_WEB_FALLBACK_METHODS);
assertKnownPlatformMethods("Mobile fallback contract", HANA_PLATFORM_MOBILE_FALLBACK_METHODS);

function invokeChannel(methodName) {
  const channel = HANA_PLATFORM_INVOKE_METHODS.get(methodName);
  if (!channel) throw new Error(`Unknown Hana invoke method: ${methodName}`);
  return channel;
}

function sendChannel(methodName) {
  const channel = HANA_PLATFORM_SEND_METHODS.get(methodName);
  if (!channel) throw new Error(`Unknown Hana send method: ${methodName}`);
  return channel;
}

function eventChannel(methodName) {
  const channel = HANA_PLATFORM_EVENT_METHODS.get(methodName);
  if (!channel) throw new Error(`Unknown Hana event method: ${methodName}`);
  return channel;
}

